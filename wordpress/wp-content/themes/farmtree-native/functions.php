/** Add canonical and restrained Open Graph metadata for the private English build. */
function farmtree_native_render_social_metadata(): void
{
    if (!is_singular() && !is_front_page()) return;
    $url = is_front_page() ? home_url('/') : get_permalink();
    $title = is_front_page() ? get_bloginfo('name') : single_post_title('', false);
    $description = farmtree_native_meta_description();
    printf("\n<link rel=\"canonical\" href=\"%s\" />\n", esc_url($url));
    printf("<meta property=\"og:type\" content=\"%s\" />\n", is_singular('post') ? 'article' : 'website');
    printf("<meta property=\"og:title\" content=\"%s\" />\n", esc_attr($title));
    printf("<meta property=\"og:url\" content=\"%s\" />\n", esc_url($url));
    if ($description !== '') printf("<meta property=\"og:description\" content=\"%s\" />\n", esc_attr($description));
}
add_action('wp_head', 'farmtree_native_render_social_metadata', 6);

/**
 * Respect WordPress search visibility, with permanent loopback QA protection.
 *
 * @param array<string, bool|string> $robots Current robots directives.
 * @return array<string, bool|string>
 */
function farmtree_native_pre_release_robots(array $robots): array
{
    if (farmtree_native_private_runtime()) {
        $robots['noindex'] = true;
        $robots['nofollow'] = true;
    } elseif (is_404() || is_search() || (is_singular() && 'publish' !== get_post_status())) {
        $robots['noindex'] = true;
    }

    return $robots;
}
add_filter('wp_robots', 'farmtree_native_pre_release_robots', 99);

/** Add an explicit HTTP-level indexing safeguard for pre-release responses. */
function farmtree_native_pre_release_headers(array $headers): array
{
    if (farmtree_native_private_runtime()) {
        $headers['X-Robots-Tag'] = 'noindex, nofollow';
    }

    return $headers;
}
add_filter('wp_headers', 'farmtree_native_pre_release_headers', 99);

/** Local QA must never become indexable when production is launched. */
function farmtree_native_private_runtime(): bool
{
    return '1' !== (string) get_option('blog_public')
        || in_array(wp_parse_url(home_url('/'), PHP_URL_HOST), ['localhost', '127.0.0.1', '::1', '[::1]'], true);
}

/** Preserve approved dated News links when the host uses post-name permalinks. */
function farmtree_native_managed_news_redirect(): void
{
    if (!is_404() || !in_array($_SERVER['REQUEST_METHOD'] ?? 'GET', ['GET', 'HEAD'], true)) {
        return;
    }
    $path = wp_parse_url(wp_unslash($_SERVER['REQUEST_URI'] ?? ''), PHP_URL_PATH);
    if (!is_string($path) || !preg_match('~^/(\d{4})/(\d{2})/(\d{2})/([a-z0-9-]+)/?$~', $path, $parts)) {
        return;
    }
    $posts = get_posts([
        'post_type' => 'post', 'post_status' => 'publish', 'name' => $parts[4],
        'posts_per_page' => 2, 'meta_key' => '_farmtree_content_managed_key',
    ]);
    if (count($posts) !== 1) {
        return;
    }
    $post = $posts[0];
    $key = (string) get_post_meta($post->ID, '_farmtree_content_managed_key', true);
    if (strpos($key, 'post.en.') !== 0 || substr($post->post_date, 0, 10) !== "$parts[1]-$parts[2]-$parts[3]") {
        return;
    }
    $destination = get_permalink($post);
    if ($destination && wp_parse_url($destination, PHP_URL_PATH) !== $path) {
        wp_safe_redirect($destination, 301, 'FarmTree managed News');
        exit;
    }
}
add_action('template_redirect', 'farmtree_native_managed_news_redirect', 1);
