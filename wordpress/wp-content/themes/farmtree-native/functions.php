/**
 * Register the minimum theme supports required by the native foundation.
 */
function farmtree_native_setup(): void
{
    load_theme_textdomain('farmtree-native', get_template_directory() . '/languages');

    add_theme_support('automatic-feed-links');
    add_theme_support('editor-styles');
    add_theme_support('post-thumbnails');
    add_theme_support('responsive-embeds');
    add_theme_support('title-tag');
    add_theme_support('wp-block-styles');

    add_editor_style(['style.css', 'assets/css/editor.css']);
}
add_action('after_setup_theme', 'farmtree_native_setup');

/** Excerpts provide editor-owned meta descriptions for private English pages. */
function farmtree_native_enable_page_excerpts(): void
{
    add_post_type_support('page', 'excerpt');
}
add_action('init', 'farmtree_native_enable_page_excerpts');

/**
 * Load the native theme stylesheet on the frontend with cache-safe versioning.
 *
 * Block themes do not automatically enqueue style.css on the frontend. The
 * same file remains registered as an editor style in farmtree_native_setup().
 */
function farmtree_native_enqueue_styles(): void
{
    $style_path = get_stylesheet_directory() . '/style.css';
    $version = is_readable($style_path)
        ? (string) filemtime($style_path)
        : (string) wp_get_theme()->get('Version');

    wp_enqueue_style(
        'farmtree-native-style',
        get_stylesheet_uri(),
        [],
        $version
    );
}
add_action('wp_enqueue_scripts', 'farmtree_native_enqueue_styles');

/**
 * Load native interactions and progressive motion on the frontend.
 *
 * The script is deliberately excluded from the Block Editor so every
 * editor-owned interactive state remains visible and directly editable.
 */
function farmtree_native_enqueue_interactions(): void
{
    $script_path = get_theme_file_path('assets/js/native-interactions.js');
    $version = is_readable($script_path)
        ? (string) filemtime($script_path)
        : (string) wp_get_theme()->get('Version');

    wp_enqueue_script(
        'farmtree-native-interactions',
        get_theme_file_uri('assets/js/native-interactions.js'),
        [],
        $version,
        true
    );
}
add_action('wp_enqueue_scripts', 'farmtree_native_enqueue_interactions');

/**
 * Add runtime image hints without polluting strict core Image serialization.
 *
 * Editors remain free to replace every Homepage image. Known bundled assets
 * receive intrinsic dimensions; Media Library replacements retain the
 * attributes generated by WordPress itself.
 *
 * @param string               $block_content Rendered block HTML.
 * @param array<string, mixed> $block         Parsed block data.
 * @return string
 */
function farmtree_native_image_loading_attributes(string $block_content, array $block): string
{
    if (($block['blockName'] ?? '') !== 'core/image' || !class_exists('WP_HTML_Tag_Processor')) {
        return $block_content;
    }

    $processor = new WP_HTML_Tag_Processor($block_content);
    if (!$processor->next_tag('img')) {
        return $block_content;
    }

    $dimensions = [
        'assets/images/home/hero-field-planning-v1.jpg'                => [1672, 941],
        'assets/images/home/hero-impact-reporting-v2.jpg'              => [1672, 941],
        'assets/images/home/hero-project-teams.webp'                   => [1672, 941],
        'assets/images/home/proof-carbon.webp'                         => [1800, 1350],
        'assets/images/home/technology-model.webp'                     => [1672, 941],
        'assets/images/proof/proof-carbon-documentary-v2.jpg'          => [1122, 1402],
        'assets/images/proof/proof-farm-value-documentary-v2.jpg'      => [1122, 1402],
        'assets/images/proof/proof-cocoa-documentary-v2.jpg'           => [1122, 1402],
        'assets/images/proof/proof-water-documentary-v2.jpg'           => [1122, 1402],
        'assets/images/partners/giz.png'                               => [491, 117],
        'assets/images/partners/rabobank.png'                          => [492, 117],
        'assets/images/partners/cgiar.png'                             => [491, 117],
        'assets/images/partners/fao.png'                               => [491, 117],
        'assets/images/partners/catie.png'                             => [492, 117],
        'assets/images/partners/helvetas.png'                          => [492, 117],
        'assets/images/testimonials/generated-placeholders/portrait-01.jpg' => [720, 900],
        'assets/images/testimonials/generated-placeholders/portrait-02.jpg' => [720, 900],
        'assets/images/testimonials/generated-placeholders/portrait-03.jpg' => [720, 900],
        'assets/images/testimonials/generated-placeholders/portrait-04.jpg' => [720, 900],
        'assets/images/testimonials/generated-placeholders/portrait-05.jpg' => [720, 900],
        'assets/images/brand/farmtree-logo.webp'                       => [320, 117],
        'assets/images/team/team-field-collaboration-v1.jpg'           => [1915, 821],
    ];
    $classes = (string) ($block['attrs']['className'] ?? '');
    $source = (string) $processor->get_attribute('src');
    $theme_uri = trailingslashit(get_theme_file_uri());

    if (!str_starts_with($source, $theme_uri)) {
        return $block_content;
    }

    $relative_path = (string) wp_parse_url(substr($source, strlen($theme_uri)), PHP_URL_PATH);
    if (!isset($dimensions[$relative_path])) {
        return $block_content;
    }

    $is_primary_hero = str_contains($classes, 'ft-home-hero-slide')
        && str_contains($classes, 'is-active');
    $is_homepage_media = $relative_path !== 'assets/images/brand/farmtree-logo.webp';

    if ($is_homepage_media) {
        $processor->set_attribute('decoding', 'async');
        $processor->set_attribute('loading', $is_primary_hero ? 'eager' : 'lazy');
        if ($is_primary_hero) {
            $processor->set_attribute('fetchpriority', 'high');
        } else {
            $processor->remove_attribute('fetchpriority');
        }
    }

    [$width, $height] = $dimensions[$relative_path];
    $processor->set_attribute('width', (string) $width);
    $processor->set_attribute('height', (string) $height);

    return $processor->get_updated_html();
}
add_filter('render_block', 'farmtree_native_image_loading_attributes', 10, 2);

