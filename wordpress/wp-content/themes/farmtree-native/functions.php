/**
 * Defer only the approved large Platform animation until its viewport entry.
 * Saved core Image content remains unchanged; editorial replacements opt out.
 * Run after native image attributes (10) and documentary picture rendering (11).
 */
function farmtree_native_defer_platform_animation(string $html, array $block): string
{
    if (($block['blockName'] ?? '') !== 'core/image'
        || !in_array('ft-platform-gif', preg_split('/\s+/', trim((string) ($block['attrs']['className'] ?? ''))), true)
        || !class_exists('WP_HTML_Tag_Processor')) {
        return $html;
    }
    $processor = new WP_HTML_Tag_Processor($html);
    if (!$processor->next_tag('img')) {
        return $html;
    }
    $animation = get_theme_file_uri('assets/media/final-tools-review-11s-to-40s-2x.gif');
    if ($processor->get_attribute('src') !== $animation
        || $processor->get_attribute('srcset') !== null
        || $processor->get_attribute('sizes') !== null) {
        return $html;
    }
    $processor->set_attribute('data-ft-animation-src', $animation);
    $processor->set_attribute('src', get_theme_file_uri('assets/media/final-tools-review-11s-to-40s-poster.png'));
    return $processor->get_updated_html();
}
add_filter('render_block', 'farmtree_native_defer_platform_animation', 12, 2);

/**
 * Responsive documentary exports. Saved core Image blocks stay editor-owned.
 * Only existing, same-theme, precompiled documentary sets are transformed.
 * Replacing an image in the editor with other media leaves core output alone.
 */
function farmtree_native_documentary_picture(string $html, array $block, ?WP_Block $instance = null): string
{
    $featured = ($block['blockName'] ?? '') === 'core/post-featured-image';
    if (!in_array($block['blockName'] ?? '', array('core/image', 'core/post-featured-image'), true) || str_contains($html, '<picture')
        || !class_exists('WP_HTML_Tag_Processor')) {
        return $html;
    }
    $processor = new WP_HTML_Tag_Processor($html);
    if (!$processor->next_tag('img')) {
        return $html;
    }
    $base = trailingslashit(get_theme_file_uri()) . 'assets/images/documentary/';
    $source = (string) $processor->get_attribute('src');
    // Match the editor-selected attachment by bytes, never by post slug or title.
    // Replacing/cropping media opts out; old attachments are never rewritten.
    if (!str_starts_with($source, $base)) {
        $id = $featured ? get_post_thumbnail_id((int) ($instance->context['postId'] ?? 0)) : (int) ($block['attrs']['id'] ?? 0);
        $file = $id ? get_attached_file($id) : false;
        if (!$file || !preg_match('/^farmtree-[a-z-]+-content\.jpg$/D', basename($file))) {
            return $html;
        }
        $original = get_theme_file_path('assets/images/documentary/' . basename($file));
        static $matches = array();
        $cache_key = $file . ':' . $original;
        if (!isset($matches[$cache_key])) {
            $matches[$cache_key] = is_file($file) && is_file($original)
                && hash_file('sha256', $file) === hash_file('sha256', $original);
        }
        if (!$matches[$cache_key]) {
            return $html;
        }
        $source = $base . basename($file);
        $processor->set_attribute('src', $source);
    }
    if (!str_starts_with($source, $base)
        || !preg_match('/^(farmtree-[a-z-]+)-(hero|content)\.jpg$/D', substr($source, strlen($base)), $match)) {
        return $html;
    }
    [, $slug, $variant] = $match;
    // Blog lead/cards have verified responsive geometry. Keep the existing
    // candidates for full-height cover heroes, whose crop needs more pixels.
    $medium = $featured && is_page('blog');
    $variants = ['hero', 'content', 'card', 'preview'];
    if ($medium) {
        $variants[] = 'medium';
    }
    foreach ($variants as $size) {
        foreach (['jpg', 'webp', 'avif'] as $format) {
            if (!is_file(get_theme_file_path("assets/images/documentary/{$slug}-{$size}.{$format}"))) {
                return $html;
            }
        }
    }
    $hero = $variant === 'hero';
    $primary = $hero && str_contains((string) ($block['attrs']['className'] ?? ''), 'is-active');
    $processor->set_attribute('width', $hero ? '1920' : '1200');
    $processor->set_attribute('height', $hero ? '1080' : '900');
    $processor->set_attribute('decoding', 'async');
    // Preserve core priorities only for the primary News/Proof featured image.
    // Cards and unrelated templates keep their existing lazy-loading behavior.
    $native_priority = $featured
        && ($block['attrs']['aspectRatio'] ?? '') === '16/9'
        && (is_page('blog') || is_singular(array('post', 'proof_story')));
    if (!$native_priority) {
        $processor->set_attribute('loading', $primary ? 'eager' : 'lazy');
        if ($primary) {
            $processor->set_attribute('fetchpriority', 'high');
        } else {
            $processor->remove_attribute('fetchpriority');
        }
    }
    $sizes = $hero ? '100vw' : '(max-width: 767px) calc(100vw - 48px), 600px';
    if ($featured) {
        $sizes = ($block['attrs']['aspectRatio'] ?? '') === '4/3'
            ? '(max-width: 767px) calc(100vw - 48px), (max-width: 1023px) calc(50vw - 36px), 400px'
            : '(max-width: 767px) calc(100vw - 48px), (max-width: 1199px) 90vw, 1200px';
    }
    $set = static function (string $format) use ($base, $slug, $hero, $medium): string {
        $intermediate = $medium ? "{$base}{$slug}-medium.{$format} 800w, " : '';
        return $hero ? "{$base}{$slug}-hero.{$format} 1920w"
            : "{$base}{$slug}-preview.{$format} 480w, {$intermediate}{$base}{$slug}-content.{$format} 1200w";
    };
    $processor->set_attribute('srcset', $set('jpg'));
    $processor->set_attribute('sizes', $sizes);
    $sources = '';
    if ($hero) {
        foreach (['avif' => 'image/avif', 'webp' => 'image/webp', 'jpg' => 'image/jpeg'] as $format => $type) {
            $sources .= '<source media="(max-width: 767px)" type="' . $type . '" width="800" height="800" srcset="'
                . esc_url("{$base}{$slug}-card.{$format}") . '" />';
        }
    }
    foreach (['avif' => 'image/avif', 'webp' => 'image/webp'] as $format => $type) {
        $sources .= '<source type="' . $type . '" srcset="' . esc_attr($set($format)) . '" sizes="' . esc_attr($sizes) . '" />';
    }
    return preg_replace_callback('/<img\b[^>]*>/i', static function ($image) use ($sources) {
        return '<picture class="ft-documentary-picture">' . $sources . $image[0] . '</picture>';
    }, $processor->get_updated_html(), 1) ?? $html;
}
add_filter('render_block', 'farmtree_native_documentary_picture', 11, 3);

