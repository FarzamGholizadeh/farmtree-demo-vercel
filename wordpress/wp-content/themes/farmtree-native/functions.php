{
    add_post_type_support('page', 'excerpt');
}
add_action('init', 'farmtree_native_enable_page_excerpts');

/**
 * Load the native theme stylesheet on the frontend with cache-safe versioning.
 *
 * Block themes do not automatically enqueue style.css on the frontend. The
 * same file remains registered as an editor style in farmtree_native_setup().
 */
function farmtree_native_enqueue_styles(): void
{
    $style_path = get_stylesheet_directory() . '/style.css';
    $version = is_readable($style_path)
        ? (string) filemtime($style_path)
        : (string) wp_get_theme()->get('Version');

    wp_enqueue_style(
        'farmtree-native-style',
        get_stylesheet_uri(),
        [],
        $version
    );
}
add_action('wp_enqueue_scripts', 'farmtree_native_enqueue_styles');

/**
 * Load native interactions and progressive motion on the frontend.
 *
 * The script is deliberately excluded from the Block Editor so every
 * editor-owned interactive state remains visible and directly editable.
 */
function farmtree_native_enqueue_interactions(): void
{
    $script_path = get_theme_file_path('assets/js/native-interactions.js');
    $version = is_readable($script_path)
        ? (string) filemtime($script_path)
        : (string) wp_get_theme()->get('Version');

    wp_enqueue_script(
        'farmtree-native-interactions',
        get_theme_file_uri('assets/js/native-interactions.js'),
        [],
        $version,
        true
    );
}
add_action('wp_enqueue_scripts', 'farmtree_native_enqueue_interactions');

