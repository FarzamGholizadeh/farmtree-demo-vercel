        'assets/images/partners/helvetas.png'                          => [492, 117],
        'assets/images/testimonials/generated-placeholders/portrait-01.jpg' => [720, 900],
        'assets/images/testimonials/generated-placeholders/portrait-02.jpg' => [720, 900],
        'assets/images/testimonials/generated-placeholders/portrait-03.jpg' => [720, 900],
        'assets/images/testimonials/generated-placeholders/portrait-04.jpg' => [720, 900],
        'assets/images/testimonials/generated-placeholders/portrait-05.jpg' => [720, 900],
        'assets/images/brand/farmtree-logo.webp'                       => [320, 117],
        'assets/images/team/team-field-collaboration-v1.jpg'           => [1915, 821],
    ];
    $classes = (string) ($block['attrs']['className'] ?? '');
    $source = (string) $processor->get_attribute('src');
    $theme_uri = trailingslashit(get_theme_file_uri());

    if (!str_starts_with($source, $theme_uri)) {
        return $block_content;
    }

    $relative_path = (string) wp_parse_url(substr($source, strlen($theme_uri)), PHP_URL_PATH);
    if (!isset($dimensions[$relative_path])) {
        return $block_content;
    }

    $is_primary_hero = str_contains($classes, 'ft-home-hero-slide')
        && str_contains($classes, 'is-active');
    $is_homepage_media = $relative_path !== 'assets/images/brand/farmtree-logo.webp';

    if ($is_homepage_media) {
        $processor->set_attribute('decoding', 'async');
        $processor->set_attribute('loading', $is_primary_hero ? 'eager' : 'lazy');
        if ($is_primary_hero) {
            $processor->set_attribute('fetchpriority', 'high');
        } else {
            $processor->remove_attribute('fetchpriority');
        }
    }

    [$width, $height] = $dimensions[$relative_path];
    $processor->set_attribute('width', (string) $width);
    $processor->set_attribute('height', (string) $height);

    return $processor->get_updated_html();
}
